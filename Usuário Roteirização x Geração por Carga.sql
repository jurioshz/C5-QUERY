select X.NROEMPRESA EMPRESA, TO_CHAR(X.DTAHORGERACAO, 'DD/MM/YYYY') as DATA_GERACAO, TO_CHAR(X.DTAHORGERACAO, 'HH24:MI:SS') as HORA_GERACAO,
X.NROCARGA CARGA, Y.SEQLOTE LOTE, Z.TIPLOTE || ' - ' || XI.DESCLINHASEPAR as LINHA_SEPARACAO, Y.SEQPRODUTO SEQPRODUTO,
XII.DESCCOMPLETA PRODUTO, X.USUGERACAO USUARIO_ROTEIRIZACAO,
(select LISTAGG(distinct XIII.USUMOVTO, ', ') within group (order by XIII.USUMOVTO)
from CONSINCO.MLO_ENDERECOMOVTO XIII
where XIII.NROEMPRESA = Y.NROEMPRESA
and XIII.NROCARGA = Y.NROCARGA and XIII.CODDEPOSSEPAR = Y.CODDEPOSSEPAR
and XIII.SEQLOTE = Y.SEQLOTE and XIII.SEQPRODUTO = Y.SEQPRODUTO
and XIII.CODDEPOSITANTE = Y.CODDEPOSITANTE and XIII.INDENTRADASAIDA = 'S') as USUARIO_GERACAO
from CONSINCO.MLO_CARGAEXPED X,
(select distinct XIV.NROEMPRESA, XIV.NROCARGA, XIV.CODDEPOSSEPAR, XIV.SEQLOTE, XIV.SEQPRODUTO, XIV.CODDEPOSITANTE
from CONSINCO.MLO_CARGAEPRODUTO XIV) Y,
(select distinct XV.NROEMPRESA, XV.NROCARGA, XV.CODDEPOSSEPAR,
XV.SEQLOTE, XV.TIPLOTE, XV.CODDISTRIBLINHA
from CONSINCO.MLO_CARGAEPALETE XV) Z, CONSINCO.MLO_LINHASEPARACAO XI, CONSINCO.MLO_PRODUTO XII
where Y.NROEMPRESA = X.NROEMPRESA
and Y.NROCARGA = X.NROCARGA
and Y.CODDEPOSSEPAR = X.CODDEPOSSEPAR
and Z.NROEMPRESA(+) = Y.NROEMPRESA
and Z.NROCARGA(+) = Y.NROCARGA
and Z.CODDEPOSSEPAR(+) = Y.CODDEPOSSEPAR
and Z.SEQLOTE(+) = Y.SEQLOTE
and XI.CODLINHASEPAR(+) = Z.TIPLOTE
and XI.CODDISTRIBLINHA(+) = Z.CODDISTRIBLINHA
and XI.NROEMPRESA(+) = Z.NROEMPRESA
and XII.SEQPRODUTO = Y.SEQPRODUTO
and XII.NROEMPRESA = Y.CODDEPOSITANTE
and X.NROEMPRESA = 507
and X.NROCARGA = 2808526
