select Z.DETALHE, Z.EMB_COMPRA,
round(sum(Z.QUANTIDADE), 3) QUANTIDADE,
round(sum(Z.PESOBRUTO), 3) PESO_BRUTO,
round(sum(Z.PESOLIQUIDO), 3) PESO_LIQUIDO,
round(sum(Z.VOLUMEM3), 3) VOLUME_M3
from (
select decode(nvl(substr(#LS2, 1, 1), 'D'), 'D', to_char(X.DTAMOVIMENTO, 'DD/MM/YYYY') || ' ' || upper(to_char(X.DTAMOVIMENTO, 'DY', 'NLS_DATE_LANGUAGE=''BRAZILIAN PORTUGUESE''')),
'C', (select max(XIV.CATEGORIA)
from CONSINCO.MAP_FAMDIVCATEG XIII, CONSINCO.MAP_CATEGORIA XIV
where XIII.SEQFAMILIA = XI.SEQFAMILIA
and XIII.NRODIVISAO = XV.NRODIVISAO
and XIII.STATUS = 'A'
and XIV.SEQCATEGORIA = XIII.SEQCATEGORIA
and XIV.NRODIVISAO = XIII.NRODIVISAO
and XIV.NIVELHIERARQUIA = 1
and XIV.TIPCATEGORIA = 'M'),
'P', Y.SEQPRODUTO || ' - ' || XI.DESCCOMPLETA) DETALHE,
decode(nvl(substr(#LS2, 1, 1), 'D'), 'D', to_char(X.DTAMOVIMENTO, 'YYYYMMDD'), null) ORDEM,
decode(nvl(substr(#LS2, 1, 1), 'D'), 'P', XII.EMBALAGEM || ' ' || XII.QTDEMBALAGEM, null) EMB_COMPRA,
Y.QUANTIDADE / nvl(XII.QTDEMBALAGEM, 1) QUANTIDADE,
Y.QUANTIDADE / nvl(XII.QTDEMBALAGEM, 1) * nvl(XII.PESOBRUTO, 0) PESOBRUTO,
Y.QUANTIDADE / nvl(XII.QTDEMBALAGEM, 1) * nvl(XII.PESOLIQUIDO, 0) PESOLIQUIDO,
Y.QUANTIDADE / nvl(XII.QTDEMBALAGEM, 1) * (nvl(XII.ALTURA, 0) * nvl(XII.LARGURA, 0) * nvl(XII.PROFUNDIDADE, 0) / 1000000) VOLUMEM3
from CONSINCO.MFL_DOCTOFISCAL X, CONSINCO.MFL_DFITEM Y, CONSINCO.MAP_PRODUTO XI,
CONSINCO.MAX_EMPRESA XV, CONSINCO.MAP_FAMDIVISAO XVI, CONSINCO.MAP_FAMEMBALAGEM XII
where Y.NROEMPRESA = X.NROEMPRESA
and Y.NUMERODF = X.NUMERODF
and Y.SERIEDF = X.SERIEDF
and Y.NROSERIEECF = X.NROSERIEECF
and XI.SEQPRODUTO = Y.SEQPRODUTO
and XV.NROEMPRESA = X.NROEMPRESA
and XVI.SEQFAMILIA = XI.SEQFAMILIA
and XVI.NRODIVISAO = XV.NRODIVISAO
and XII.SEQFAMILIA = XI.SEQFAMILIA
and XII.QTDEMBALAGEM = XVI.PADRAOEMBCOMPRA
and X.STATUSDF = 'V'
and X.CODGERALOPER in (93, 95, 261, 850, 64, 96)
and X.NROEMPRESA in (#LS1)
and X.DTAMOVIMENTO between :DT1 and :DT2
) Z
group by Z.DETALHE, Z.ORDEM, Z.EMB_COMPRA
order by Z.ORDEM, Z.DETALHE
