select X.NROEMPRESA EMPRESA,
X.DTALANCAMENTO DATA_LANCAMENTO,
to_char(X.DTAHORLANCAMENTO, 'HH24:MI:SS') HORA,
to_char(X.DTAHORINICIO, 'DD/MM/YYYY HH24:MI:SS') INICIO,
to_char(X.DTAHORFIM, 'DD/MM/YYYY HH24:MI:SS') FIM,
lpad(trunc(nvl(X.TEMPO, 0) / 60), 2, '0') || ':' || to_char(trunc(sysdate) + mod(nvl(X.TEMPO, 0), 60) / 1440, 'MI:SS') TEMPO,
round(X.TEMPO, 2) TEMPO_MINUTOS,
X.MESANO || '/' || X.SEQTAREFA TAREFA,
X.QTDATIVIDADE QTDE_ATIVIDADE,
X.PESO PESO,
X.METRAGEMCUBICA METRAGEM_CUBICA,
X.QTDVOLUME QTDE_VOLUMES,
X.QTDITEM QTDE_ITENS,
Z.CODEQUIPE || nvl2(XI.EQUIPE, ' - ' || XI.EQUIPE, null) EQUIPE,
X.CODPRODUTIVO COD_PRODUTIVO,
Z.NOMEREDUZ PRODUTIVO,
X.CODTIPATIVIDADE || ' - ' || Y.ATIVIDADE ATIVIDADE,
X.CODDISTRIBLINHA || nvl2(X.CODDISTRIBLINHA, ' - ' || (select max(XIV.DESCDISTRIBLINHA) from CONSINCO.MLO_DISTRIBUICAOLINHA XIV where XIV.CODDISTRIBLINHA = X.CODDISTRIBLINHA), null) DISTRIBUICAO,
X.CODLINHASEPAR || nvl2(X.CODLINHASEPAR, ' - ' || (select max(XV.DESCLINHASEPAR) from CONSINCO.MLO_LINHASEPARACAO XV where XV.CODLINHASEPAR = X.CODLINHASEPAR and XV.CODDISTRIBLINHA = X.CODDISTRIBLINHA), null) LINHA_SEPARACAO,
X.VALORPRODUTIVIDADE VALOR_PRODUTIVIDADE,
decode(X.ORIGEMLANCAMENTO, 'A', 'AUTOMATICO', 'M', 'MANUAL', X.ORIGEMLANCAMENTO) TIPO_LANCAMENTO,
XII.DESCRICAO TIPO_MOVIMENTACAO,
decode(X.FATOR, 'A', 'Atividade', 'R', 'Valor', 'P', 'Peso', 'M', 'Metragem Cubica', 'V', 'Qtde Volumes', 'I', 'Qtde Itens') FATOR,
X.QTDFATOR VALOR_FATOR,
X.NROCARGA CARGA,
X.SEQLOTE LOTE
from CONSINCO.MLO_PRODUTIVIDADE X,
CONSINCO.MLO_TIPATIVIDADE Y,
CONSINCO.MLO_PRODUTIVO Z,
CONSINCO.MLO_EQUIPE XI,
CONSINCO.MLO_TIPOMOVIMENTO XII
where Y.CODTIPATIVIDADE = X.CODTIPATIVIDADE
and Y.NROEMPRESA = X.NROEMPRESA
and Z.CODPRODUTIVO = X.CODPRODUTIVO
and Z.NROEMPRESA = X.NROEMPRESA
and XI.CODEQUIPE(+) = Z.CODEQUIPE
and XI.NROEMPRESA(+) = Z.NROEMPRESA
and XII.TIPMOVTO(+) = X.TIPMOVTO
and XII.NROEMPRESA(+) = X.NROEMPRESA
and X.SEQPRODUTIVIDADEINC is null
and not exists (select 1 from CONSINCO.MLO_PRODUTIVIDADE XIII where XIII.SEQPRODUTIVIDADEINC = X.SEQPRODUTIVIDADE and XIII.NROEMPRESA = X.NROEMPRESA)
--and X.CODTIPATIVIDADE in (select XVI.CODTIPATIVIDADE from CONSINCO.MLO_TIPATIVIDADE XVI group by XVI.CODTIPATIVIDADE having XVI.CODTIPATIVIDADE || ' - ' || max(XVI.ATIVIDADE) in (#LS1))
--and X.DTALANCAMENTO between :DT1 and :DT2
